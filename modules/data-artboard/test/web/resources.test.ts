// Only the repository's generated TTF is used. The second resolver receives an
// in-memory metrics variant; no additional font file is written or committed.
function testFont(advance = 600): Buffer {
  const original = readFileSync('fixtures/fonts/anima-test.ttf');
  if (advance === 600) return original;
  const tables = new Map<string, Buffer>();
  for (let i = 0; i < original.readUInt16BE(4); i++) {
    const at = 12 + i * 16,
      offset = original.readUInt32BE(at + 8),
      length = original.readUInt32BE(at + 12);
    tables.set(
      original.toString('ascii', at, at + 4),
      Buffer.from(original.subarray(offset, offset + length)),
    );
  }
  const hhea = tables.get('hhea')!,
    hmtx = tables.get('hmtx')!;
  for (let i = 0; i < hhea.readUInt16BE(34); i++) hmtx.writeUInt16BE(advance, i * 4);
  hhea.writeUInt16BE(advance, 10);
  return sfnt(tables);
}

for (const [engineName, engine, executable] of [
  [
    'Chromium',
    chromium,
    '.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell',
  ],
  ['Firefox', firefox, '.cache/ms-playwright/firefox-1555/firefox/firefox'],
] as const)
  for (const fontsFirst of [false, true])
    it(`${engineName} adopts unused image/font components, scoped by source load (${fontsFirst ? 'fonts' : 'assets'} first)`, async () => {
      const executablePath = [resolve(homedir(), executable), engine.executablePath()].find(
        existsSync,
      );
      const browser = await engine.launch({ executablePath, headless: true });
      try {
        const page = await browser.newPage();
        await page.setContent(
          '<base href="https://anima.test/"><anima-icon id="a" paused auto-bind></anima-icon><anima-icon id="b" paused auto-bind></anima-icon><anima-icon id="target" auto-bind style="display:block;width:200px;height:200px"></anima-icon><anima-icon id="other" auto-bind style="display:block;width:200px;height:200px"></anima-icon>',
        );
        for (const entry of [
          ...(fontsFirst
            ? ['data-artboard-values', 'data-artboard']
            : ['data-artboard', 'data-artboard-values']),
          'components',
          'paint',
          'bind',
          'data',
          'host',
          ...(fontsFirst ? ['fonts-text', 'assets'] : ['assets', 'fonts-text']),
          'text',
          'canvas',
        ])
          await page.addScriptTag({
            type: 'module',
            content: await cachedBundle(resolve('packages/web/src/' + entry + '.ts')),
          });
        await page.waitForFunction(() =>
          ['assets', 'fonts', 'data', 'text', 'dataartboard'].every((name) =>
            (customElements.get('anima-icon') as typeof AnimaIcon)?.modules.has(name),
          ),
        );
        // Relative font URLs are served from our generated bytes; image resolver returns a Blob.
        await page.route('https://anima.test/normal.ttf', (route) =>
          route.fulfill({ contentType: 'font/ttf', body: Buffer.from(testFont()) }),
        );
        await page.route('https://anima.test/wide.ttf', (route) =>
          route.fulfill({ contentType: 'font/ttf', body: Buffer.from(testFont(900)) }),
        );
        const loaded = await page.evaluate(async (nested) => {
          const [a, b, target, other] = [...document.querySelectorAll('anima-icon')] as AnimaIcon[];
          const requires = [
            'assets',
            'paint',
            'fonts',
            'text',
            'components',
            'bind',
            'data',
            'nested',
            'host',
            'dataartboard',
          ];
          const data = {
            models: { Card: { properties: { content: { type: 'artboard', default: '' } } } },
          };
          const image = {
            id: 'photo',
            type: 'image',
            asset: 'tile',
            x0: 0,
            y0: 0,
            width: 5,
            height: 5,
          };
          const label = {
            id: 'label',
            type: 'text',
            x: 0,
            y: 8,
            width: 20,
            height: 5,
            styles: { body: { font: 'body', size: 2 } },
            runs: [{ text: 'AAA', style: 'body' }],
            fill: { color: '#00ff00' },
          };
          const raw = {
            anima: '0.1',
            name: 'resource-source',
            grid: 20,
            requires,
            data,
            assets: {
              tile: { type: 'image', source: 'tile.svg' },
              body: { type: 'font', source: 'font.ttf' },
            },
            components: {
              unused: {
                grid: 20,
                nodes: nested
                  ? [{ id: 'inner', type: 'instance', component: 'leaf' }]
                  : [image, label],
              },
              leaf: { grid: 20, nodes: [image, label] },
            },
            nodes: [{ id: 'empty', type: 'group', children: [] }],
          };
          const resolver = (color: string, font: string) => (name: string) =>
            name === 'tile'
              ? new Blob(
                  [
                    `<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><path fill="${color}" d="M0 0H2V2H0Z"/></svg>`,
                  ],
                  { type: 'image/svg+xml' },
                )
              : font;
          a!.assets = resolver('#ff0000', 'normal.ttf');
          b!.assets = resolver('#0000ff', 'wide.ttf');
          const load = async (icon: AnimaIcon, doc: object) => {
            const errors = icon.load(doc).filter((d) => d.severity === 'error');
            if (errors.length) throw Error(JSON.stringify(errors));
            await icon.ready;
          };
          // The identical object exercises compiled-model sharing and resolver isolation.
          await load(a!, raw);
          await load(b!, raw);
          const dest = {
            ...raw,
            name: 'destination',
            components: { own: { grid: 20, nodes: [image, label] } },
            nodes: [{ id: 'slot', type: 'instance', component: '$content' }],
          };
          target!.assets = resolver('#00ff00', 'wide.ttf');
          other!.assets = target!.assets;
          await load(target!, dest);
          await load(other!, {
            anima: '0.1',
            name: 'no-resources',
            grid: 20,
            data,
            nodes: dest.nodes,
            requires: ['components', 'bind', 'data', 'nested', 'host', 'dataartboard'],
            components: {
              own: { grid: 20, nodes: [{ id: 'empty', type: 'group', children: [] }] },
            },
          });
          const va = target!.component(a!.player!.model, 'unused'),
            vb = target!.component(b!.player!.model, 'unused');
          window.artboards = { va, vb, load, raw, dest };
          target!.data.artboard('content').set(va);
          other!.data.artboard('content').set(vb);
          target!.player!.step(0);
          other!.player!.step(0);
          target!.invalidate();
          other!.invalidate();
          return {
            sourceUnplaced: a!.shadowRoot!.querySelectorAll('image').length,
            sameCatalog: a!.player!.model.doc === b!.player!.model.doc,
            distinctLoads: a!.player!.model !== b!.player!.model,
          };
        }, fontsFirst);
        expect(loaded.sourceUnplaced).toBe(0);
        expect(loaded.sameCatalog).toBe(true);
        expect(loaded.distinctLoads).toBe(true);
        const widths = () =>
          page.evaluate(() =>
            ['target', 'other'].map((id) => {
              const icon = document.getElementById(id) as AnimaIcon;
              const span = icon.shadowRoot!.querySelector('tspan') as SVGTextContentElement | null;
              return span?.getComputedTextLength() ?? 0;
            }),
          );
        await expect.poll(widths).toEqual([expect.closeTo(3.6, 1), expect.closeTo(5.4, 1)]);
        const before = await page.evaluate(async () => {
          const frames = () =>
            new Promise<void>((res) =>
              requestAnimationFrame(() => requestAnimationFrame(() => res())),
            );
          await frames();
          const target = document.getElementById('target') as AnimaIcon,
            a = document.getElementById('a') as AnimaIcon,
            b = document.getElementById('b') as AnimaIcon;
          const families = [
            ...target.shadowRoot!.querySelectorAll('tspan'),
            ...document.getElementById('other')!.shadowRoot!.querySelectorAll('tspan'),
          ].map((span) => getComputedStyle(span).fontFamily);
          const { load, raw } = window.artboards;
          await load(a, raw);
          a.destroy();
          b.destroy();
          return families;
        });
        expect(before.join()).toContain('anima-font-');
        await expect.poll(widths).toEqual([expect.closeTo(3.6, 1), expect.closeTo(5.4, 1)]);
        const released = await page.evaluate(async (families) => {
          const target = document.getElementById('target') as AnimaIcon,
            other = document.getElementById('other') as AnimaIcon;
          for (const icon of [target, other]) {
            icon.data.artboard('content').set('');
            icon.player!.step(0);
            icon.invalidate();
          }
          await new Promise<void>((res) =>
            requestAnimationFrame(() => requestAnimationFrame(() => res())),
          );
          const retained = [...document.fonts].some((face) =>
            families.some(
              (family) => family?.replace(/["']/g, '') === face.family.replace(/["']/g, ''),
            ),
          );
          target.data.artboard('content').set(window.artboards.va);
          other.data.artboard('content').set(window.artboards.vb);
          target.player!.step(0);
          other.player!.step(0);
          target.invalidate();
          other.invalidate();
          return retained;
        }, before);
        expect(released).toBe(false);
        await expect.poll(widths).toEqual([expect.closeTo(3.6, 1), expect.closeTo(5.4, 1)]);
        for (const [id, expected] of [
          ['target', [255, 0, 0, 255]],
          ['other', [0, 0, 255, 255]],
        ] as const) {
          await page.evaluate((id) => {
            const icon = document.getElementById(id) as AnimaIcon;
            icon.setAttribute('renderer', 'canvas');
            icon.invalidate();
          }, id);
          await expect
            .poll(() =>
              page.evaluate(async (id) => {
                await new Promise<void>((res) =>
                  requestAnimationFrame(() => requestAnimationFrame(() => res())),
                );
                const canvas = document.getElementById(id)!.shadowRoot!.querySelector('canvas');
                return canvas ? [...canvas.getContext('2d')!.getImageData(20, 20, 1, 1).data] : [];
              }, id),
            )
            .toEqual(expected);
        }
        const textPixels = await page.evaluate(() =>
          ['target', 'other'].map((id) => {
            const canvas = document.getElementById(id)!.shadowRoot!.querySelector('canvas')!;
            const data = canvas.getContext('2d')!.getImageData(0, 60, 200, 100).data;
            let green = 0;
            for (let i = 0; i < data.length; i += 4)
              if (data[i + 1]! > 200 && data[i]! < 20 && data[i + 2]! < 20 && data[i + 3]! > 200)
                green++;
            return green;
          }),
        );
        expect(textPixels.every((count) => count > 100)).toBe(true);
        const cleanup = await page.evaluate(async () => {
          const target = document.getElementById('target') as AnimaIcon,
            other = document.getElementById('other') as AnimaIcon;
          // Retained handles still work after their source hosts are destroyed.
          target.data.artboard('content').set(window.artboards.vb);
          target.player!.step(0);
          target.invalidate();
          await new Promise<void>((res) =>
            requestAnimationFrame(() => requestAnimationFrame(() => res())),
          );
          other.destroy();
          const during = [...document.fonts]
            .filter((face) => face.family.startsWith('anima-font-'))
            .map((f) => f.family);
          target.destroy();
          return {
            during: during.length,
            after: [...document.fonts].filter((face) => face.family.startsWith('anima-font-'))
              .length,
          };
        });
        expect(cleanup.during).toBeGreaterThan(0);
        expect(cleanup.after).toBe(0);
      } finally {
        await browser.close();
      }
    }, 30_000);

