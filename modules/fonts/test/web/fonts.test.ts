import { existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { resolve } from 'node:path';
import { chromium, firefox, type Page } from 'playwright-core';
import { describe, expect, it } from 'vitest';
import { cachedBundle as bundle } from '../../../../tools/browser-cache.ts';
import { testFont } from '../font.ts';
import type { AnimaIcon } from '../../../../packages/web/src/index.ts';
import type {} from '../../web/index.ts';
import type {} from '../../../host/web/index.ts';

async function ready(page: Page, names = ['assets', 'fonts']) {
  await page.waitForFunction(
    (names) => {
      const Icon = customElements.get('anima-icon') as typeof AnimaIcon | undefined;
      return (
        !!Icon &&
        names.every((name) => Icon.modules.has(name)) &&
        !!Object.getOwnPropertyDescriptor(Icon.prototype, 'fonts')
      );
    },
    names,
    { polling: 10 },
  );
}

for (const [name, browserType, executablePath] of [
  [
    'Chromium',
    chromium,
    resolve(
      homedir(),
      '.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell',
    ),
  ],
  ['Firefox', firefox, resolve(homedir(), '.cache/ms-playwright/firefox-1555/firefox/firefox')],
] as const) {
  describe.skipIf(!existsSync(executablePath))(name + ' fonts', () => {
    it('loads generated bytes before load; scopes replacements, CSS features, fallback weight and cleanup', async () => {
      const browser = await browserType.launch({ executablePath, headless: true });
      try {
        const page = await browser.newPage();
        await page.setContent('<anima-icon paused></anima-icon><anima-icon paused></anima-icon>');
        for (const entry of ['assets', 'fonts'])
          await page.addScriptTag({
            type: 'module',
            content: await bundle(resolve('packages/web/src/' + entry + '.ts')),
          });
        // A separately bundled text consumer may also import the fonts entry.
        await page.addScriptTag({
          type: 'module',
          content: await bundle(resolve('packages/web/src/fonts.ts')),
        });
        await ready(page);
        const result = await page.evaluate(
          async ({ bytes, wide, accented }) => {
            const icons = [...document.querySelectorAll('anima-icon')] as AnimaIcon[];
            const spec = {
              family: 'body, monospace',
              size: 20,
              weight: 400,
              style: 'normal' as const,
              tracking: 1,
              axes: { wght: 625 },
              features: { liga: 0, kern: 1 },
            };
            const doc = {
              anima: '0.1',
              name: 'fonts',
              grid: 20,
              requires: ['assets', 'fonts'],
              assets: {
                body: {
                  type: 'font',
                  source: 'data:font/ttf;base64,' + btoa(String.fromCharCode(...bytes)),
                },
              },
              nodes: [{ id: 'dot', type: 'circle', center: [10, 10], r: 1 }],
            };
            const earlyFace = new FontFace('host-before', new Uint8Array(accented).buffer);
            await icons[0]!.fonts.add(earlyFace);
            await Promise.all(
              icons.map(
                (icon) =>
                  new Promise<void>((res, rej) => {
                    icon.addEventListener('anima:load', () => res(), { once: true });
                    icon.addEventListener(
                      'anima:error',
                      (e) => rej(new Error(JSON.stringify((e as CustomEvent).detail))),
                      {
                        once: true,
                      },
                    );
                    icon.load(doc);
                  }),
              ),
            );
            const [a, b] = icons as [AnimaIcon, AnimaIcon];
            const measure = (icon: AnimaIcon) => {
              const context = document.createElement('canvas').getContext('2d')!;
              context.font = icon.fonts.cssFont(spec).font;
              const m = context.measureText('AAA');
              return { width: m.width, ascent: m.fontBoundingBoxAscent };
            };
            await a.fonts.ready(spec, 'AAA');
            const beforeLoadFallback = document.fonts.has(earlyFace);
            const revision = a.fonts.revision;
            const before = measure(a),
              other = measure(b);
            await a.fonts.set('body', new Uint8Array(wide).buffer);
            const after = measure(a),
              unchanged = measure(b);
            const style = a.fonts.cssFont(spec);
            const face = await a.fonts.decode(new Uint8Array(bytes).buffer);
            await a.fonts.add(face, { weight: 700 });
            const fallback = a.fonts.cssFont({ ...spec, family: 'absent' }).fontFamily;
            const regular = new FontFace('host-fallback', new Uint8Array(bytes).buffer, {
              weight: '400',
            });
            const bold = new FontFace('host-fallback', new Uint8Array(wide).buffer, {
              weight: '700',
            });
            await a.fonts.add(regular, { weight: 400 });
            await a.fonts.add(bold, { weight: 700 });
            const ctx = document.createElement('canvas').getContext('2d')!;
            // Request the shared host family explicitly to verify browser weight matching.
            ctx.font = a.fonts.cssFont({ ...spec, family: 'host-fallback', weight: 400 }).font;
            const regularWidth = ctx.measureText('AAA').width;
            ctx.font = a.fonts.cssFont({ ...spec, family: 'host-fallback', weight: 700 }).font;
            const boldWidth = ctx.measureText('AAA').width;
            const accent = await a.fonts.decode(new Uint8Array(accented).buffer);
            await a.fonts.add(accent);
            ctx.font = a.fonts.cssFont({ ...spec, family: 'body', weight: 400 }).font;
            const glyphFallback = ctx.measureText('Ā').width;
            const retained = document.fonts.has(face);
            a.fonts.clear();
            return {
              beforeLoadFallback,
              revisionChanged: a.fonts.revision > revision,
              earlyFaceRemoved: !document.fonts.has(earlyFace),
              regularWidth,
              boldWidth,
              glyphFallback,
              before,
              other,
              after,
              unchanged,
              style,
              fallback,
              weight: face.weight,
              retained,
              removed: !document.fonts.has(face),
              otherStillLoaded: measure(b).width,
            };
          },
          { bytes: testFont(), wide: testFont(900), accented: testFont(900, 256, 256) },
        );
        expect(result.beforeLoadFallback && result.revisionChanged && result.earlyFaceRemoved).toBe(
          true,
        );
        expect(result.glyphFallback).toBeCloseTo(18, 1);
        expect(result.regularWidth).toBeCloseTo(36, 1);
        expect(result.boldWidth).toBeCloseTo(54, 1);
        expect(result.before.width).toBeCloseTo(36, 1);
        expect(result.after.width).toBeCloseTo(54, 1);
        expect(result.other.width).toEqual(result.unchanged.width);
        expect(result.otherStillLoaded).toBeCloseTo(36, 1);
        expect(result.before.ascent).toBeGreaterThan(0);
        expect(result.style.fontVariationSettings).toBe('"wght" 625');
        expect(result.style.fontFeatureSettings).toBe('"liga" 0, "kern" 1');
        expect(result.style.letterSpacing).toBe('1px');
        expect(result.fallback).toContain('anima-font-');
        expect(result.weight).toBe('700');
        expect(result.retained && result.removed).toBe(true);
      } finally {
        await browser.close();
      }
    }, 30000);
    it.each([false, true])(
      'initializes fonts for shared models in both entry orders (fonts first=%s)',
      async (fontsFirst) => {
        const browser = await browserType.launch({ executablePath, headless: true });
        try {
          const page = await browser.newPage();
          await page.setContent('<anima-icon paused></anima-icon><anima-icon paused></anima-icon>');
          for (const entry of [
            ...(fontsFirst ? ['fonts', 'assets'] : ['assets', 'fonts']),
            'host-edit',
            'data',
            'host',
          ])
            await page.addScriptTag({
              type: 'module',
              content: await bundle(resolve('packages/web/src/' + entry + '.ts')),
            });
          await ready(page, ['assets', 'fonts', 'hostedit', 'data', 'host']);
          const families = await page.evaluate(async (bytes) => {
            const Icon = customElements.get('anima-icon') as typeof AnimaIcon;
            const compiled = (
              Icon.modules.get(
                'hostedit',
              ) as typeof import('../../../host-edit/core/index.ts').hostEdit
            ).compile!({
              anima: '0.1',
              name: 'cache',
              grid: 20,
              requires: ['assets', 'fonts'],
              assets: {
                body: {
                  type: 'font',
                  source: 'data:font/ttf;base64,' + btoa(String.fromCharCode(...bytes)),
                },
              },
              nodes: [{ id: 'dot', type: 'circle', center: [10, 10], r: 1 }],
            });
            if (!compiled.model) throw compiled.diagnostics;
            const families: string[] = [];
            for (const icon of document.querySelectorAll('anima-icon') as NodeListOf<AnimaIcon>) {
              const loaded = new Promise<void>((res, rej) => {
                icon.addEventListener('anima:load', () => res(), { once: true });
                icon.addEventListener(
                  'anima:error',
                  (e) => rej(new Error(JSON.stringify((e as CustomEvent).detail))),
                  {
                    once: true,
                  },
                );
              });
              icon.loadModel(compiled.model);
              await loaded;
              families.push(
                icon.fonts.cssFont({
                  family: 'body',
                  size: 20,
                  weight: 400,
                  style: 'normal',
                  tracking: 0,
                }).fontFamily,
              );
            }
            return families;
          }, testFont());
          expect(families).toHaveLength(2);
          expect(families.every((f) => f.includes('anima-font-'))).toBe(true);
          expect(families[0]).not.toBe(families[1]);
        } finally {
          await browser.close();
        }
      },
      30000,
    );
    it('assigns decoded fonts through typed data handles without changing other properties or icons', async () => {
      const browser = await browserType.launch({ executablePath, headless: true });
      try {
        const page = await browser.newPage();
        await page.setContent('<anima-icon paused auto-bind></anima-icon>');
        for (const entry of ['fonts', 'assets', 'data', 'host'])
          await page.addScriptTag({
            type: 'module',
            content: await bundle(resolve('packages/web/src/' + entry + '.ts')),
          });
        await ready(page);
        await ready(page, ['assets', 'fonts', 'data', 'host']);
        const result = await page.evaluate(async (bytes) => {
          const icon = document.querySelector('anima-icon') as AnimaIcon;
          icon.assets = (name, info) =>
            name === 'photo'
              ? new Blob(
                  [
                    '<svg xmlns="http://www.w3.org/2000/svg" width="2" height="3"><rect width="2" height="3" fill="red"/></svg>',
                  ],
                  { type: 'image/svg+xml' },
                )
              : info.source;
          const loaded = new Promise<void>((resolve, reject) => {
            icon.addEventListener('anima:load', () => resolve(), { once: true });
            icon.addEventListener(
              'anima:error',
              (e) => reject(new Error(JSON.stringify((e as CustomEvent).detail))),
              {
                once: true,
              },
            );
          });
          icon.load({
            anima: '0.1',
            name: 'data-font',
            grid: 20,
            requires: ['data', 'assets', 'fonts'],
            assets: {
              body: {
                type: 'font',
                source: 'data:font/ttf;base64,' + btoa(String.fromCharCode(...bytes)),
              },
              photo: { type: 'image', source: 'photo.svg' },
            },
            nodes: [{ id: 'dot', type: 'circle', center: [10, 10], r: 1 }],
            data: {
              models: {
                Root: {
                  properties: {
                    first: { type: 'asset-ref', assetType: 'font', default: 'body' },
                    second: { type: 'asset-ref', assetType: 'font', default: 'body' },
                  },
                },
              },
            },
          });
          await loaded;
          const face = await icon.fonts.decode(new Uint8Array(bytes).buffer);
          await icon.data.font('$first').set(face);
          icon.player!.step(0);
          const first = icon.data.font('$first').value;
          const photo = (customElements.get('anima-icon') as typeof AnimaIcon).modules.get(
            'assets',
          ) as typeof import('../../../assets/core/index.ts').assets;
          const retainedImage = photo.resolvedAssets.get(icon.player!)!.photo!;
          return {
            photoSource: retainedImage.source,
            photoWidth: retainedImage.width,
            photoHeight: retainedImage.height,
            first,
            second: icon.data.font('$second').value,
            family: icon.fonts.cssFont({
              family: first,
              size: 20,
              weight: 400,
              style: 'normal',
              tracking: 0,
            }).fontFamily,
          };
        }, testFont());
        expect(result.photoSource).toMatch(/^data:image\/svg\+xml/);
        expect([result.photoWidth, result.photoHeight]).toEqual([2, 3]);
        expect(result.first).toMatch(/^font-/);
        expect(result.second).toBe('body');
        expect(result.family).toContain('anima-font-');
      } finally {
        await browser.close();
      }
    }, 30000);
    it('reports policy/decode failures as structured warnings and preserves fallback', async () => {
      const browser = await browserType.launch({ executablePath, headless: true });
      try {
        const page = await browser.newPage();
        await page.setContent('<anima-icon paused></anima-icon>');
        for (const entry of ['assets', 'fonts'])
          await page.addScriptTag({
            type: 'module',
            content: await bundle(resolve('packages/web/src/' + entry + '.ts')),
          });
        await ready(page);
        const result = await page.evaluate(async () => {
          const icon = document.querySelector('anima-icon') as AnimaIcon;
          const warnings: unknown[] = [];
          icon.addEventListener('anima:warning', (e) =>
            warnings.push(...(e as CustomEvent).detail),
          );
          const loaded = new Promise<void>((res, rej) => {
            icon.addEventListener('anima:load', () => res(), { once: true });
            icon.addEventListener(
              'anima:error',
              (e) => rej(new Error(JSON.stringify((e as CustomEvent).detail))),
              {
                once: true,
              },
            );
          });
          icon.load({
            anima: '0.1',
            name: 'bad',
            grid: 20,
            requires: ['assets', 'fonts'],
            assets: {
              bad: { type: 'font', source: 'https://example.invalid/font.ttf' },
              broken: { type: 'font', source: 'data:font/ttf;base64,AQID' },
            },
            nodes: [{ id: 'dot', type: 'circle', center: [10, 10], r: 1 }],
          });
          await loaded;
          return {
            warnings,
            family: icon.fonts.cssFont({
              family: 'bad, serif',
              size: 20,
              weight: 400,
              style: 'normal',
              tracking: 0,
            }).fontFamily,
          };
        });
        expect(result.warnings).toHaveLength(2);
        expect(result.warnings).toEqual(
          expect.arrayContaining([
            expect.objectContaining({
              code: 'font-load',
              pointer: '/assets/bad/source',
              severity: 'warning',
              message: expect.any(String),
              hint: expect.any(String),
            }),
          ]),
        );
        expect(result.family).toBe('bad, serif');
      } finally {
        await browser.close();
      }
    }, 30000);
  });
}
