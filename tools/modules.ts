// Discover module-owned manifests; generated adapters preserve the public package boundaries.
// node tools/modules.ts [--check] [--root <fixture-root>]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { format } from 'prettier';

export interface Manifest {
  name: string;
  /** One line for `anima features`: what the module lets a scene do (browser/authoring entries say so). */
  summary?: string;
  after: string[];
  core?: { entry: string; export: string; svg?: string; svgExport?: string } | null;
  web: {
    name: string;
    budget: number;
    over?: string;
    heavy?: boolean;
    /** Authoring add-on (in-browser compiler, inspectors): measured on top of core+web, not in page totals. */
    authoring?: boolean;
    sizeOrder?: number;
    buildOrder?: number;
  }[];
  adapters: Record<string, string>;
  exports: Record<string, string>;
  markupHook?: {
    slot: string;
    type: string;
    value: string;
    browserName?: string;
    browserBase?: string;
  } | null;
  tests: string[];
  conformance: string[];
  docs: string[];
}
export async function discover(root: string): Promise<Manifest[]> {
  const found: Manifest[] = [];
  for (const dir of readdirSync(resolve(root, 'modules')).sort()) {
    const path = resolve(root, 'modules', dir, 'manifest.ts');
    if (!existsSync(path)) continue;
    const m = (await import(pathToFileURL(path).href)).default as Manifest;
    if (m.name !== dir) throw Error(`module directory/name mismatch: ${dir}`);
    for (const file of [...Object.values(m.adapters), ...(m.core ? [m.core.entry] : [])])
      if (!existsSync(resolve(root, 'modules', dir, file))) throw Error(`${dir}: missing ${file}`);
    for (const doc of m.docs)
      if (!existsSync(resolve(root, doc))) throw Error(`${dir}: missing docs ${doc}`);
    found.push(m);
  }
  return ordered(found);
}
export function ordered(manifests: Manifest[]): Manifest[] {
  const result: Manifest[] = [];
  const pending = new Map(
    manifests.map((m) => [m.name, m]).sort(([a], [b]) => (a! < b! ? -1 : a! > b! ? 1 : 0)) as [
      string,
      Manifest,
    ][],
  );
  for (const m of manifests)
    for (const name of m.after)
      if (!pending.has(name)) throw Error(`${m.name}: unknown after dependency ${name}`);
  while (pending.size) {
    const ready = [...pending.values()].find((m) => m.after.every((name) => !pending.has(name)));
    if (!ready) throw Error('module dependency cycle');
    result.push(ready);
    pending.delete(ready.name);
  }
  return result;
}

const banner = '// Generated by tools/modules.ts; edit modules/<name>/manifest.ts instead.\n';
export async function generate(root: string, check = false): Promise<string[]> {
  const manifests = await discover(root);
  const stale: string[] = [];
  const emit = async (path: string, source: string) => {
    const text = await format(source, {
      parser: path.endsWith('package.json')
        ? 'json-stringify'
        : path.endsWith('.json')
          ? 'json'
          : 'typescript',
      singleQuote: true,
      printWidth: 100,
    });
    const target = resolve(root, path);
    if (existsSync(target) && readFileSync(target, 'utf8') === text) return;
    stale.push(path);
    if (!check) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
  };
  const importPath = (from: string, to: string) => {
    const path = relative(dirname(from), to).replaceAll('\\', '/');
    return path.startsWith('.') ? path : './' + path;
  };
  const entries = new Set(['index']);
  const budgets: Manifest['web'] = [];
  const hooks: (NonNullable<Manifest['markupHook']> & { path: string })[] = [];
  for (const m of manifests) {
    for (const [path, local] of Object.entries(m.adapters))
      await emit(
        path,
        `${banner}export * from '${importPath(path, `modules/${m.name}/${local}`)}';\n`,
      );
    for (const entry of m.web) {
      if (entries.has(entry.name)) throw Error(`duplicate browser entry ${entry.name}`);
      entries.add(entry.name);
      budgets.push(entry);
    }
    if (m.markupHook) hooks.push({ ...m.markupHook, path: `modules/${m.name}/markup/index.ts` });
  }
  const cores = manifests.filter((m) => m.core);
  let all = `${banner}import { VERBOSE } from './flags.ts';\nimport { registerModule } from './modules.ts';\nimport { registerSVGBackend } from './svg.ts';\n`;
  for (const m of cores) {
    const c = m.core!;
    all += `import { ${c.export} } from '${importPath('packages/core/src/all.ts', `modules/${m.name}/${c.entry}`)}';\n`;
    if (c.svg)
      all += `import { ${c.svgExport} } from '${importPath('packages/core/src/all.ts', `modules/${m.name}/${c.svg}`)}';\n`;
  }
  all += 'if (VERBOSE) {\n';
  for (const m of cores) {
    const c = m.core!;
    all += `registerModule(${c.export});\n`;
    if (c.svg) all += `registerSVGBackend('${m.name}', ${c.svgExport});\n`;
  }
  await emit('packages/core/src/all.ts', all + '}\n');
  let registry = `${banner}import { VERBOSE } from '@anima-format/core';\n`;
  for (const h of hooks) {
    registry += `import { ${[h.type, h.browserBase].filter(Boolean).join(', ')} } from '${importPath('packages/markup/src/module-hooks.ts', h.path)}';\n`;
    registry += `export const ${h.slot}: Partial<typeof ${h.type}> = {};\nif (VERBOSE) Object.assign(${h.slot}, ${h.value});\n`;
  }
  registry += 'export function prepareModuleMarkup(hooks: Record<string, object>): void {\n';
  for (const h of hooks)
    registry += `Object.assign(${h.slot}, ${h.browserBase ? h.browserBase + ', ' : ''}hooks['${h.browserName ?? h.slot}']);\n`;
  registry += '}\n';
  await emit('packages/markup/src/module-hooks.ts', registry);
  // Every runtime browser module, for tests and tools that must play any document (not a page
  // entry: pages import only what they use).
  await emit(
    'packages/web/src/all-modules.ts',
    banner +
      [...entries]
        .filter((e) => e !== 'index' && !e.startsWith('markup'))
        .sort()
        .map((e) => `import './${e}.ts';\n`)
        .join(''),
  );
  await emit(
    'tools/modules.generated.ts',
    `${banner}export const webEntries = ${JSON.stringify([
      'index',
      ...budgets
        .slice()
        .sort((a, b) => (a.buildOrder ?? 999) - (b.buildOrder ?? 999))
        .map((e) => e.name),
    ])};\nexport const webOwners: Record<string, string> = ${JSON.stringify(Object.fromEntries(manifests.flatMap((m) => m.web.map((e) => [e.name, m.name]))))};\nexport const moduleBudgets: { name: string; budget: number; over?: string; heavy?: boolean; authoring?: boolean; sizeOrder?: number; buildOrder?: number }[] = ${JSON.stringify(budgets.sort((a, b) => (a.sizeOrder ?? 999) - (b.sizeOrder ?? 999)))};\nexport const moduleScopes = ${JSON.stringify(Object.fromEntries(manifests.map((m) => [m.name, { tests: m.tests, conformance: m.conformance }])))};\n`,
  );
  // Own the module export set, leaving the base package API under package ownership.
  // Existing generated adapters identify old module exports, including removed modules.
  for (const pkg of ['core', 'markup', 'web']) {
    const path = `packages/${pkg}/package.json`;
    const data = JSON.parse(readFileSync(resolve(root, path), 'utf8'));
    const exports: Record<string, string> = {};
    for (const [key, value] of Object.entries(data.exports) as [string, string][]) {
      const target = resolve(root, 'packages', pkg, value);
      if (
        key === './all' ||
        (existsSync(target) && readFileSync(target, 'utf8').startsWith(banner + 'export *'))
      )
        continue;
      exports[key] = value;
    }
    if (pkg === 'core') exports['./all'] = './src/all.ts';
    for (const m of manifests)
      for (const [key, target] of Object.entries(m.exports))
        if (key.startsWith(pkg + ':'))
          exports[key.slice(pkg.length + 1)] = './' + target.split('/').slice(2).join('/');
    data.exports = exports;
    await emit(path, JSON.stringify(data));
  }
  return stale;
}
if (process.argv[1] && resolve(process.argv[1]) === resolve(new URL(import.meta.url).pathname)) {
  const rootArg = process.argv.indexOf('--root');
  const root =
    rootArg < 0
      ? resolve(new URL('../', import.meta.url).pathname)
      : resolve(process.argv[rootArg + 1]!);
  const check = process.argv.includes('--check');
  const stale = await generate(root, check);
  if (check && stale.length) {
    console.error(`Stale module wiring: ${stale.join(', ')}. Run node tools/modules.ts`);
    process.exitCode = 1;
  } else
    console.log(
      `Module wiring ${check ? 'current' : 'generated'} (${stale.length} files ${check ? 'stale' : 'updated'})`,
    );
}
