import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  COMMANDS,
  GLOBAL,
  GROUPS,
  type Command,
  type Option,
} from '../packages/cli/src/commands.ts';

const ROOT = resolve(import.meta.dirname, '..');
const TARGET = resolve(ROOT, 'docs/CLI.md');

function option(option: Option): string {
  const names = [
    option.short ? `-${option.short}` : '',
    `--${option.name}${option.value ? ` <${option.value}>` : ''}`,
  ]
    .filter(Boolean)
    .join(', ');
  const extra = [
    option.default ? `default: ${option.default}` : '',
    option.multiple ? 'repeatable' : '',
  ]
    .filter(Boolean)
    .join('; ');
  return `- \`${names}\` — ${option.summary}${extra ? ` (${extra})` : ''}`;
}

function commandDoc(command: Command): string {
  const lines = [`### \`anima ${command.name}\``, '', command.summary, '', '**Usage**', ''];
  lines.push(...command.usage.map((usage) => `- \`anima ${usage}\``));
  const options = [...command.options, ...GLOBAL];
  if (options.length) lines.push('', '**Options**', '', ...options.map(option));
  if (command.examples.length) {
    lines.push('', '**Examples**', '');
    for (const example of command.examples)
      lines.push(`- \`anima ${example.run}\` — ${example.note}`);
  }
  if (command.see?.length)
    lines.push('', `**See also:** ${command.see.map((entry) => `\`${entry}\``).join(', ')}`);
  return lines.join('\n');
}

function generate(): string {
  const lines = [
    '# Anima CLI reference',
    '',
    '<!-- Generated by tools/cli-docs.ts. Do not edit by hand. -->',
    '',
    'This reference is generated from the command table used by `anima help`.',
  ];
  for (const [group, title] of Object.entries(GROUPS)) {
    const commands = COMMANDS.filter((command) => command.group === group);
    if (!commands.length) continue;
    lines.push('', `## ${title}`, '');
    for (const command of commands) lines.push(commandDoc(command), '');
    while (lines.at(-1) === '') lines.pop();
  }
  lines.push('');
  return lines.join('\n');
}

const expected = generate();
if (process.argv.includes('--check')) {
  let actual: string;
  try {
    actual = readFileSync(TARGET, 'utf8');
  } catch {
    actual = '';
  }
  if (actual !== expected) {
    console.error('docs/CLI.md is stale; run node tools/cli-docs.ts');
    process.exitCode = 1;
  }
} else {
  writeFileSync(TARGET, expected);
}
