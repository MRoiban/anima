#!/usr/bin/env python3
"""Golden vectors for spec §5 eases, from an implementation independent of packages/core.

Cubic: exact root of Bx(s) = u by 200 rounds of bisection in Python floats (Bx is monotonic for
x1, x2 in [0, 1]); elastic: the closed form. Writes spec/conformance/eases.json.

    python3 tools/gen_eases.py
"""
import json
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "spec" / "conformance" / "eases.json"

NAMED = {"in": (0.42, 0, 1, 1), "out": (0, 0, 0.58, 1), "inOut": (0.42, 0, 0.58, 1)}


def bez(s, p1, p2):
    r = 1 - s
    return 3 * r * r * s * p1 + 3 * r * s * s * p2 + s ** 3


def cubic(x1, y1, x2, y2, u):
    if u <= 0:
        return 0.0
    if u >= 1:
        return 1.0
    lo, hi = 0.0, 1.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if bez(mid, x1, x2) < u:
            lo = mid
        else:
            hi = mid
    return bez((lo + hi) / 2, y1, y2)


def elastic(a, p, u):
    if u <= 0:
        return 0.0
    if u >= 1:
        return 1.0
    A = max(a, 1)
    s = p / (2 * math.pi) * math.asin(1 / A)
    return A * 2 ** (-10 * u) * math.sin((u - s) * 2 * math.pi / p) + 1


EASES = [
    "linear", "hold", "in", "out", "inOut",
    "cubic(0.2, 0, 0.3, 1)", "cubic(0.45, 0, 0.55, 1)", "cubic(0.6, 0, 0.9, 0.6)",
    "cubic(0, 0, 0, 0)", "cubic(1, 1, 1, 1)", "cubic(0, 0, 1, 1)", "cubic(1, 0, 0, 1)",
    "cubic(0.34, 1.56, 0.64, 1)", "cubic(0.5, -0.8, 0.5, 1.8)", "cubic(0,1,1,0)",
    "elastic(1, 0.45)", "elastic(1, 0.3)", "elastic(2, 0.5)", "elastic(0.5, 0.25)",
]
U = [i / 40 for i in range(41)] + [1e-6, 0.001, 0.123456, 0.5 - 1e-9, 0.999, 0.999999]


def evaluate(ease, u):
    if ease == "linear":
        return u
    if ease == "hold":
        return 0.0
    if ease in NAMED:
        return cubic(*NAMED[ease], u)
    name, args = ease.split("(")
    v = [float(x) for x in args.rstrip(")").split(",")]
    return cubic(*v, u) if name == "cubic" else elastic(*v, u)


def main():
    cases = [{"ease": e, "u": U, "w": [evaluate(e, u) for u in U]} for e in EASES]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"$comment": "Generated by tools/gen_eases.py. Compare at 1e-7.", "cases": cases}, indent=1) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
